// The Studio home (/home): one prompt, Image | Video. Image runs text-to-image (feature "create")
// through the registry like every tool, one job and one charge per image; results are saved to
// History as mode "create" (no SKU, so they're never uploaded to a store). Video (paid plans) is a
// background job per clip: checked and queued here, generated by the worker (src/lib/video), and
// polled by the page; its credits are reserved when the provider call starts.

const MAX_REFERENCE_BYTES = 10 * 1024 * 1024;

const toItem = (g: Generation): StudioItem => ({
  id: g.id,
  kind: "image",
  status: "ok",
  url: `/api/assets/${g.assetId}`,
  width: g.width,
  height: g.height,
  prompt: g.title,
  aspectRatio: g.settings.aspectRatio ?? null,
  seconds: null,
  error: null,
  createdBy: g.createdBy,
  createdAt: g.createdAt,
});

const toVideoItem = (j: VideoJob): StudioItem => {
  // Display box only (the player letterboxes): 1280 px on the long edge.
  const [w, h] = ratioParts(j.settings.aspectRatio);
  const scale = 1280 / Math.max(w, h);
  return {
    id: j.id,
    kind: "video",
    status: j.status,
    url: j.assetId ? `/api/assets/${j.assetId}` : null,
    width: Math.round(w * scale),
    height: Math.round(h * scale),
    prompt: j.prompt,
    aspectRatio: j.settings.aspectRatio,
    seconds: j.settings.seconds,
    error: j.error,
    createdBy: j.createdBy,
    createdAt: j.createdAt,
  };
};

export async function getStudioSetup(): Promise<StudioSetup> {
  const workspace = await getWorkspace();
  const [{ creditRules, disabledFeatures }, video] = await Promise.all([getPlatformSettings(), videoModelFor(workspace.orgId)]);
  const model = video.ok ? video.model : DEFAULT_VIDEO_MODEL;
  return {
    plan: workspace.plan,
    canCreate: workspace.role !== "viewer",
    imageAllowed: planAllows(creditRules, workspace.plan, "create") && !disabledFeatures.includes("create"),
    videoAllowed: planAllows(creditRules, workspace.plan, "video"),
    videoDisabled: disabledFeatures.includes("video"),
    videoProblem: video.ok ? null : video.code,
    videoCaps: videoCapabilities(model),
    imageCost: creditRules.featureCosts.create,
    video: creditRules.video satisfies CreditRules["video"],
    creditsRemaining: workspace.creditsRemaining,
  };
}

/** Recent images and videos, newest first. */
export async function listStudioRecent(): Promise<StudioItem[]> {
  const workspace = await getWorkspace();
  const [images, videos] = await Promise.all([listRecentGenerations(workspace.orgId, "create", 24), listRecentVideoJobs(workspace.orgId, 24)]);
  return [...images.map(toItem), ...videos.map(toVideoItem)].sort((a, b) => b.createdAt.localeCompare(a.createdAt));
}

/** Current state of video jobs the page is waiting on. */
export async function pollStudioVideos(ids: string[]): Promise<StudioItem[]> {
  const workspace = await getWorkspace();
  const clean = (Array.isArray(ids) ? ids : []).filter((id) => typeof id === "string" && /^[0-9a-f-]{36}$/.test(id)).slice(0, 50);
  return (await getVideoJobs(workspace.orgId, clean)).map(toVideoItem);
}

export type StartVideoResult =
  | { ok: true; item: StudioItem }
  | { ok: false; error: ProviderErrorCode | "invalid_input" | "forbidden" | "not_enough_credits" | "too_many_jobs" };

/**
 * Checks a video request (plan, model capabilities, credits, per-org limit) and queues it. The
 * credits are reserved when the worker starts the provider call, and given back if it fails.
 */
export async function startVideo(formData: FormData): Promise<StartVideoResult> {
  const workspace = await getWorkspace();
  if (workspace.role === "viewer") return { ok: false, error: "forbidden" };
  const { creditRules, disabledFeatures } = await getPlatformSettings();
  if (disabledFeatures.includes("video")) return { ok: false, error: "feature_disabled" };
  if (!planAllows(creditRules, workspace.plan, "video")) return { ok: false, error: "not_in_plan" };

  const prompt = String(formData.get("prompt") ?? "").trim();
  const settings = {
    aspectRatio: String(formData.get("aspectRatio") ?? ""),
    seconds: Number(formData.get("seconds")),
    resolution: String(formData.get("resolution") ?? ""),
    camera: String(formData.get("camera") ?? ""),
    motion: String(formData.get("motion") ?? ""),
  };
  const frame = formData.get("startFrame");
  const startFrame = frame instanceof File && frame.size > 0 ? frame : null;

  const video = await videoModelFor(workspace.orgId);
  if (!video.ok) return { ok: false, error: video.code };
  const valid =
    prompt.length > 0 &&
    prompt.length <= PROMPT_MAX &&
    fitsCapabilities(videoCapabilities(video.model), { ...settings, hasStartFrame: startFrame !== null }) &&
    (CAMERA_MOVES as readonly string[]).includes(settings.camera) &&
    (MOTION_LEVELS as readonly string[]).includes(settings.motion) &&
    (startFrame === null || (PRODUCT_IMAGE_TYPES.includes(startFrame.type) && startFrame.size <= MAX_REFERENCE_BYTES));
  if (!valid) return { ok: false, error: "invalid_input" };

  const credits = videoCost(creditRules, { seconds: settings.seconds, resolution: settings.resolution as VideoSettings["resolution"] });
  if (credits > workspace.creditsRemaining) return { ok: false, error: "not_enough_credits" };
  if ((await countOpenVideoJobs(workspace.orgId)) >= MAX_OPEN_VIDEO_JOBS) return { ok: false, error: "too_many_jobs" };

  const frameAsset = startFrame ? await saveAsset(workspace.orgId, new Uint8Array(await startFrame.arrayBuffer()), startFrame.type, "video-frame") : null;
  const job = await insertVideoJob({
    orgId: workspace.orgId,
    prompt,
    settings: settings as VideoSettings,
    startFrameAssetId: frameAsset,
    startFrameMime: startFrame?.type ?? null,
    credits,
    createdBy: workspace.user.name,
    createdById: workspace.user.id,
  });
  await dispatchVideoJob(workspace.orgId, job.id);
  return { ok: true, item: toVideoItem(job) };
}

export type CreateImagesResult =
  | { ok: true; items: StudioItem[]; failed: number; error: ProviderErrorCode | null }
  | { ok: false; error: ProviderErrorCode | "invalid_input" | "forbidden" };

export async function createImages(formData: FormData): Promise<CreateImagesResult> {
  const workspace = await getWorkspace();
  if (workspace.role === "viewer") return { ok: false, error: "forbidden" };

  const prompt = String(formData.get("prompt") ?? "").trim();
  const aspectRatio = String(formData.get("aspectRatio") ?? "");
  const resolution = String(formData.get("resolution") ?? "");
  const count = Number(formData.get("count"));
  const files = formData.getAll("reference").filter((f): f is File => f instanceof File && f.size > 0);
  const valid =
    prompt.length > 0 &&
    prompt.length <= PROMPT_MAX &&
    (CREATE_ASPECT_RATIOS as readonly string[]).includes(aspectRatio) &&
    (resolution === "HD" || resolution === "2K") &&
    Number.isInteger(count) &&
    count >= 1 &&
    count <= STUDIO_MAX_IMAGES &&
    files.length <= STUDIO_MAX_REFERENCES &&
    files.every((f) => PRODUCT_IMAGE_TYPES.includes(f.type) && f.size <= MAX_REFERENCE_BYTES);
  if (!valid) return { ok: false, error: "invalid_input" };

  const references = await Promise.all(files.map(async (f) => ({ bytes: new Uint8Array(await f.arrayBuffer()), mimeType: f.type, name: f.name })));
  const provider = await getImageProvider(workspace, "create");
  const request = { prompt, aspectRatio: aspectRatio as CreateAspectRatio, resolution: resolution as "HD" | "2K", references };

  const results = await Promise.allSettled(Array.from({ length: count }, () => provider.createImage(request)));
  const items: StudioItem[] = [];
  let error: ProviderErrorCode | null = null;
  for (const result of results) {
    if (result.status === "fulfilled") {
      const saved = await save(workspace, result.value, { prompt, aspectRatio, resolution, references: String(references.length) });
      if (saved) items.push(saved);
      else error ??= "generation_failed";
      continue;
    }
    const code = result.reason instanceof ProviderError ? result.reason.code : "generation_failed";
    if (!(result.reason instanceof ProviderError)) reportError("Studio image failed", result.reason, { orgId: workspace.orgId, feature: "create" });
    error ??= code;
  }
  if (!items.length) return { ok: false, error: error ?? "generation_failed" };
  // Credits were used: the top bar's credit badge re-reads them.
  refresh();
  return { ok: true, items, failed: count - items.length, error };
}

async function save(workspace: Awaited<ReturnType<typeof getWorkspace>>, image: GeneratedImage, settings: Record<string, string>) {
  const decoded = await decodeImage(image.url);
  if (!decoded) return null;
  const assetId = await saveAsset(workspace.orgId, decoded.bytes, decoded.mimeType, "generation");
  const generation = await insertGeneration({
    orgId: workspace.orgId,
    mode: "create",
    sku: "",
    title: settings.prompt.slice(0, 120),
    assetId,
    mimeType: decoded.mimeType,
    width: image.width,
    height: image.height,
    settings,
    provider: image.provider,
    model: image.model,
    createdBy: workspace.user.name,
  });
  return toItem(generation);
}
